import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const projectsRoot = path.join(root, "assets", "images", "projects");
const output = path.join(root, "js", "project-gallery-data.js");
const imageExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);

function encodePathPart(value) {
  return encodeURIComponent(value).replace(/%2F/g, "/");
}

const galleries = {};

if (fs.existsSync(projectsRoot)) {
  for (const folder of fs.readdirSync(projectsRoot, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    const folderPath = path.join(projectsRoot, folder.name);
    const images = fs.readdirSync(folderPath, { withFileTypes: true })
      .filter(entry => entry.isFile() && imageExtensions.has(path.extname(entry.name).toLowerCase()))
      .map(entry => `assets/images/projects/${encodePathPart(folder.name)}/${encodePathPart(entry.name)}`)
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
    galleries[folder.name] = images;
  }
}

const contents = `// AUTO-GENERATED by scripts/build-project-galleries.mjs\n// Do not edit this file manually. Add/remove image files inside a project's folder instead.\nconst PROJECT_GALLERIES = ${JSON.stringify(galleries, null, 2)};\n`;
fs.writeFileSync(output, contents, "utf8");
console.log(`Built ${Object.keys(galleries).length} project galleries.`);
